# Operaciones matemáticas básicas
a = 10
b = 3

suma = a + b              # 13
resta = a - b             # 7
multiplicacion = a * b    # 30
division = a / b          # 3.3333...
division_entera = a // b  # 3
modulo = a % b            # 1 (residuo de la división)
exponenciacion = a ** b   # 1000

print(f"Suma: {suma}")
print(f"Multiplicación: {multiplicacion}")
print(f"Módulo (residuo): {modulo}")