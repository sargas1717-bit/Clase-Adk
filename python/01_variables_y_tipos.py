# Declaración de variables y tipos de datos básicos
nombre = "Carlos"          # Texto (str)
edad = 25                  # Entero (int)
estatura = 1.75            # Decimal (float)
activo = True              # Booleano (bool)

print("Tipo de dato de nombre:", type(nombre))
print("Tipo de dato de edad:", type(edad))
print("Tipo de dato de estatura:", type(estatura))
print("Tipo de dato de activo:", type(activo))
