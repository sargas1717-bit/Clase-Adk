# Comparaciones que devuelven resultados booleanos (True o False)
x = 10
y = 20

es_mayor = x > y          # False
es_menor = x < y          # True
es_igual = x == y         # False
es_diferente = x != y     # True
mayor_o_igual = x >= 10   # True
menor_o_igual = y <= 15   # False

print("¿Es x mayor que y?:", es_mayor)
print("¿Es x menor que y?:", es_menor)
print("¿Es x igual a y?:", es_igual)
print("¿Es x diferente de y?:", es_diferente)